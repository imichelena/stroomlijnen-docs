import test from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
const url = new URL('../src/utils/readingStorage.mjs', import.meta.url);
test('reading storage: safe, locale-separated, validated, observable persistence', async () => {
 assert.ok(existsSync(url), 'reading storage module exists');
 const s = await import(url);
 const data = new Map(); const events = [];
 global.window = {localStorage: {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)},dispatchEvent:e=>events.push(e)};
 global.CustomEvent = class {constructor(type,options){this.type=type;this.detail=options.detail}};
 assert.deepEqual(s.listBookmarks('nl'), []);
 assert.deepEqual(s.toggleBookmark('nl',{path:'/docs/test',title:'Test'}),{ok:true,bookmarked:true});
 assert.equal(s.listBookmarks('nl')[0].title,'Test');
 assert.equal(s.isBookmarked('nl','/docs/test'),true);
 assert.deepEqual(s.listBookmarks('en'),[]);
 assert.equal(events[0].type,s.READING_EVENT);
 assert.equal(s.toggleBookmark('nl',{path:'https://evil.test',title:'Bad'}).ok,false);
 assert.equal(s.toggleBookmark('nl',{path:'//evil.test',title:'Bad'}).ok,false);
 assert.equal(s.toggleBookmark('nl',{path:'/docs/test',title:'Test'}).bookmarked,false);
 assert.equal(s.saveReadingPosition('en',{path:'/en/docs/test',title:'English',progress:.4}),true);
 assert.equal(s.getReadingPosition('en','/en/docs/test').progress,.4);
 assert.equal(s.getReadingPosition('nl','/en/docs/test'),null);
 assert.equal(s.listRecentReading('en').length,1);
 assert.equal(s.saveReadingPosition('en',{path:'/en/docs/bad',title:'Bad',progress:NaN}),false);
 assert.equal(s.saveReadingSettings({fontSize:'large',width:'wide',focus:true}),true);
 assert.deepEqual(s.getReadingSettings(),{fontSize:'large',width:'wide',focus:true});
 for(const key of data.keys()) data.set(key,'{bad');
 assert.deepEqual(s.listBookmarks('nl'),[]);
 assert.deepEqual(s.listRecentReading('en'),[]);
 assert.deepEqual(s.getReadingSettings(),{fontSize:'standard',width:'standard',focus:false});
 for(const key of data.keys()) data.set(key,JSON.stringify([{path:'javascript:alert(1)',title:'Bad',updatedAt:1}]));
 assert.deepEqual(s.listBookmarks('nl'),[]);
 Object.defineProperty(window,'localStorage',{get(){throw Error('blocked')}});
 assert.deepEqual(s.listBookmarks('nl'),[]);
 assert.equal(s.toggleBookmark('nl',{path:'/docs/test',title:'Test'}).ok,false);
 assert.equal(s.saveReadingSettings({}),false);
 delete global.window;
 assert.deepEqual(s.listRecentReading('nl'),[]);
});
test('article-relative progress, target and reading-time math',async()=>{
 const url = new URL('../src/utils/readingMetrics.mjs',import.meta.url);
 assert.ok(existsSync(url),'reading metrics module exists');
 const {articleProgress,resumeTarget,readingMinutes} = await import(url);
 assert.equal(articleProgress({top:200,height:1800},800),0);
 assert.equal(articleProgress({top:-500,height:1800},800),.5);
 assert.equal(articleProgress({top:-1500,height:1800},800),1);
 assert.equal(articleProgress({top:20,height:400},800),1);
 assert.equal(resumeTarget({top:-200,height:1800},800,700,.5),1000);
 assert.equal(readingMinutes('word '.repeat(401)),3);
 assert.equal(readingMinutes(''),1);
});
