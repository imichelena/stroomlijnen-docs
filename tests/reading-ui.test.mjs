import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
const require = createRequire(import.meta.url);
const {JSDOM} = createRequire('/tmp/reading-test-deps/package.json')('jsdom');
const React = require('react');
const {act} = React;
const {createRoot} = require('react-dom/client');
const ts = require('typescript');
const componentURL = new URL('../src/components/ReadingTools/index.tsx',import.meta.url);
async function loadComponent() {
 let code = ts.transpileModule(readFileSync(componentURL,'utf8'),{compilerOptions:{jsx:ts.JsxEmit.React,module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
 code = code.replace(/import ['"]\.\/styles.css['"];?/g,'');
 code = code.replace(/from ['"]([^'"]+)['"]/g,(_,spec)=>`from '${spec.startsWith('.') ? new URL(spec,componentURL).href : pathToFileURL(require.resolve(spec)).href}'`);
 return (await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'))).default;
}
test('toolbar: localised controls, persistence, resume opt-in, errors, focus and unmount cleanup',async()=>{
 assert.ok(existsSync(componentURL),'ReadingTools component exists');
 const dom = new JSDOM('<div id="root"></div><div class="theme-doc-markdown"><h1>Guide</h1><p>Article text</p></div>',{url:'https://docs.test/docs/guide'});
 Object.assign(global,{window:dom.window,document:dom.window.document,CustomEvent:dom.window.CustomEvent,IS_REACT_ACT_ENVIRONMENT:true});
 Object.defineProperty(global,'navigator',{value:dom.window.navigator,configurable:true});
 global.requestAnimationFrame = cb => setTimeout(cb,0);global.cancelAnimationFrame=clearTimeout;
 window.requestAnimationFrame=global.requestAnimationFrame;window.cancelAnimationFrame=clearTimeout;
 const article=document.querySelector('.theme-doc-markdown');
 article.getBoundingClientRect=()=>({top:0,height:2000});
 let jumps=0;window.scrollTo=()=>{jumps++};let printed=0;window.print=()=>{printed++};
 const storage=await import('../src/utils/readingStorage.mjs');
 storage.saveReadingPosition('nl',{path:'/docs/guide',title:'Guide',progress:.45});
 const Component=await loadComponent();const root=createRoot(document.getElementById('root'));
 await act(async()=>root.render(React.createElement(Component,{locale:'nl',path:'/docs/guide',title:'Guide'})));
 const button=text=>[...document.querySelectorAll('button')].find(b=>b.textContent===text);
 const click=async text=>{assert.ok(button(text),`button ${text}`);await act(async()=>button(text).click())};
 assert.equal(jumps,0,'never automatically restores scroll');
 assert.match(document.body.textContent,/min lezen/);
 assert.ok(document.querySelector('progress[aria-label="Leesvoortgang"]'));
 await click('Hervat lezen');assert.equal(jumps,1);
 await click('Bewaren');assert.equal(button('Bewaard').getAttribute('aria-pressed'),'true');
 assert.equal(storage.listBookmarks('nl').length,1);assert.equal(storage.listBookmarks('en').length,0);
 await click('Afdrukken');assert.equal(printed,1);
 Object.defineProperty(navigator,'clipboard',{value:{writeText:async()=>{}},configurable:true});
 await click('Link kopiëren');assert.match(document.body.textContent,/Link gekopieerd/);
 Object.defineProperty(navigator,'clipboard',{value:{writeText:async()=>{throw Error('denied')}},configurable:true});
 await click('Link kopiëren');assert.match(document.body.textContent,/Kopiëren mislukt/);
 await click('Leesinstellingen');
 const font=document.querySelector('select[aria-label="Tekstgrootte"]');assert.ok(font);
 await act(async()=>{font.value='large';font.dispatchEvent(new window.Event('change',{bubbles:true}))});
 assert.equal(document.documentElement.dataset.readingFont,'large');assert.equal(storage.getReadingSettings().fontSize,'large');
 await click('Focusmodus');assert.equal(document.documentElement.dataset.readingFocus,'true');
 await click('Focusmodus verlaten');assert.notEqual(document.documentElement.dataset.readingFocus,'true');
 await click('Focusmodus');
 await act(async()=>window.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape'})));
 assert.notEqual(document.documentElement.dataset.readingFocus,'true');
 article.getBoundingClientRect=()=>({top:-600,height:2000});
 await act(async()=>{window.dispatchEvent(new window.Event('scroll'));await new Promise(r=>setTimeout(r,10))});
 assert.ok(storage.getReadingPosition('nl','/docs/guide').progress>.4,'scroll saves article-relative progress');
 let resolveCopy;
 Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>new Promise(resolve=>{resolveCopy=resolve})},configurable:true});
 await click('Link kopiëren');
 await act(async()=>root.unmount());assert.equal(document.documentElement.dataset.readingFont,undefined);
 await act(async()=>resolveCopy());
 const before=JSON.stringify(storage.listRecentReading('nl'));
 window.dispatchEvent(new window.Event('scroll'));await new Promise(r=>setTimeout(r,20));
 assert.equal(JSON.stringify(storage.listRecentReading('nl')),before,'no stale listeners or timers after unmount');
 const root2=createRoot(document.getElementById('root'));
 await act(async()=>root2.render(React.createElement(Component,{locale:'en',path:'/en/docs/guide',title:'Guide'})));
 assert.ok(button('Save'));assert.ok(button('Copy link'));assert.ok(button('Reading settings'));
 assert.equal(button('Resume reading'),undefined);
 await act(async()=>root2.unmount());dom.window.close();
});
